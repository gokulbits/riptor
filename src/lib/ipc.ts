export const events = {
  engine: (cb: (e: EngineEvent) => void): Promise<UnlistenFn> => listen<EngineEvent>("riptor://event", (e) => cb(e.payload)),
  ready: (cb: () => void) => listen("riptor://ready", () => cb()),
  externalAdd: (cb: (items: Source[]) => void) => listen<Source[]>("riptor://external-add", (e) => cb(e.payload)),
  trayAction: (cb: (action: string) => void) => listen<string>("riptor://tray-action", (e) => cb(e.payload)),
  search: (cb: (e: SearchEvent) => void) => listen<SearchEvent>("riptor://search", (e) => cb(e.payload)),
  vpn: (cb: (s: VpnStatus) => void) => listen<VpnStatus>("riptor://vpn", (e) => cb(e.payload)),
  rss: (cb: () => void) => listen("riptor://rss", () => cb()),
  whenDone: (cb: (c: { action: WhenDone; seconds: number }) => void) =>
    listen<{ action: WhenDone; seconds: number }>("riptor://when-done", (e) => cb(e.payload)),
  updateAvailable: (cb: (u: UpdateInfo) => void) => listen<UpdateInfo>("riptor://update-available", (e) => cb(e.payload)),
  updateProgress: (cb: (p: { done: number; total: number | null }) => void) =>
    listen<{ done: number; total: number | null }>("riptor://update-progress", (e) => cb(e.payload)),
};

export function errorText(e: unknown): string {
  if (typeof e === "string") return e;
  if (e instanceof Error) return e.message;
  return JSON.stringify(e);
}
